"""Build winget/message_table.py from winget-cli's translations, so stages are understood in every language winget speaks.

    generate_messages.py <folder holding en-US.resw, de-DE.resw and the others>

Take the files from the release tag being matched: Localization/Resources/<language>/winget.resw, and for English
src/AppInstallerCLIPackage/Shared/Strings/en-us/winget.resw. They are read as plain text, without an XML parser.
"""
import html
import re
import sys
from pathlib import Path

KEYS = {
    "DOWNLOADING": "Downloading",
    "VERIFIED": "InstallerHashVerified",
    "INSTALLING": "InstallFlowStartingPackageInstall",
    "UNINSTALLING": "UninstallFlowStartingPackageUninstall",
    "PUBLISHER": "ShowLabelPublisher",
    "HOMEPAGE": "ShowLabelPackageUrl",
    "RELEASE_NOTES": "ShowLabelReleaseNotes",
}


def value(text: str, key: str) -> str:
    found = re.search(rf'<data name="{key}"[^>]*>\s*<value>(.*?)</value>', text, re.S)
    if not found:
        raise SystemExit(f"{key} is missing")
    return html.unescape(found.group(1)).strip()


folder = Path(sys.argv[1])
columns: dict[str, list[str]] = {name: [] for name in KEYS}
for path in sorted(folder.glob("*.resw")):
    text = path.read_text(encoding="utf-8")
    for name, key in KEYS.items():
        columns[name].append(value(text, key))

out = ['"""Generated by scripts/generate_messages.py from winget-cli\'s translations. Do not edit."""', ""]
for name, values in columns.items():
    unique = list(dict.fromkeys(values))
    out.append(f"{name} = (")
    out.extend(f"    {item!r}," for item in unique)
    out.append(")")
target = Path(__file__).resolve().parents[1] / "src/wingetdeck/winget/message_table.py"
target.write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(list(folder.glob("*.resw"))), "languages")
