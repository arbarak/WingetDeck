"""Build winget/code_table.py from winget-cli's returnCodes.md. Usage: generate_codes.py returnCodes.md"""
import re
import sys
from pathlib import Path

rows = re.findall(r"^\|\s*(0x[0-9A-Fa-f]{8})\s*\|\s*-?\d+\s*\|\s*(\w+)\s*\|\s*(.*?)\s*\|\s*$",
                  Path(sys.argv[1]).read_text(encoding="utf-8"), re.M)
out = ['"""Generated by scripts/generate_codes.py from winget-cli doc/.../returnCodes.md. Do not edit."""', "",
       "CODES: dict[int, tuple[str, str]] = {"]
for code, symbol, text in rows:
    symbol = symbol.replace("APPINSTALLER_CLI_ERROR_", "")
    out.append(f"    {code.upper().replace('0X', '0x')}: ({symbol!r}, {text!r}),")
out.append("}")
Path(__file__).resolve().parents[1].joinpath("src/wingetdeck/winget/code_table.py").write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(rows), "codes")
